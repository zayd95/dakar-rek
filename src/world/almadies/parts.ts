/**
 * LD2.0-E: the district's shared pieces, in the site's plan coordinates (metres from its origin, +z toward the street, x along it, y up, the ground at
 * GROUND), drawn on a `SiteDraw` into the hub's merged batches. Every piece is cheap by construction (boxes only, no hidden faces) and thins out on
 * the low preset (`d.lite`). Lanes use them as they are and draw their own designs beside them; they do not edit this file.
 *
 *   volume, slabEdge, parapet     the masses: a wall box, a slab with its overhang, a roof's parapet (glass or solid)
 *   glazing, louvres              a glazed face in slim frames; vertical slats (a brise-soleil, a claustra)
 *   balcony, canopy, pergola      a balcony (glass, bars or solid guard), a flat canopy on slim posts, a roof pergola
 *   door, nameBoard               a front door in its portal with steps and a light; a lit sign board
 *   planter, roofPlant, palm      planting, the roof's tank, solar panels and air conditioners, a palm
 *   perimeter, solidBox           the boundary wall with its gate (colliders included); a solid box
 */
export interface PlanRect { x0: number; z0: number; x1: number; z1: number }
/** The faces of a box in the plan: the street's (+z), the back's (−z), the left's (−x) and the right's (+x). */
export type Face = 'street' | 'back' | 'left' | 'right';
const along = (f: Face) => f === 'street' || f === 'back' ? 'x' as const : 'z' as const;
const out = (f: Face) => f === 'street' || f === 'right' ? 1 : -1;
/** The gate's centre along the street wall (plan x, before mirroring): the middle, or 3.4 m in from one end. */
export const gateX = (w: number, side: GateSide | 'none') => side === 'left' ? -w / 2 + 3.4 : side === 'right' ? w / 2 - 3.4 : 0;
const mid = (r: PlanRect) => ({ x: (r.x0 + r.x1) / 2, z: (r.z0 + r.z1) / 2, w: r.x1 - r.x0, dd: r.z1 - r.z0 });
/** A tiny deterministic generator from the site's id and a salt (never `Math.random`: every client draws the same street). */
export function siteRng(d: SiteDraw, salt = ''): () => number {
  let h = 2166136261; for (const ch of d.site.id + salt) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  return () => { h = Math.imul(h ^ (h >>> 15), 2246822507); h = Math.imul(h ^ (h >>> 13), 3266489909); h ^= h >>> 16; return (h >>> 0) / 4294967296; };
}

// ------------------------------------------------------------------------------------------------ masses
/** A wall box over a plan rectangle from y0 to y1. */
export function volume(d: SiteDraw, r: PlanRect, y0: number, y1: number, col: number, b: Batch = d.plain) {
  const m = mid(r); d.box(b, m.w, y1 - y0, m.dd, m.x, y0, m.z, col);
}
/** A slab (a floor's edge, a roof) with `over` m of overhang all round, its top at `y`, `thick` thick (all six faces: it is seen from below). */
export function slabEdge(d: SiteDraw, r: PlanRect, y: number, thick = 0.25, over = 0.4, col: number = d.p.slab) {
  const m = mid(r); d.slab(d.plain, m.w + 2 * over, thick, m.dd + 2 * over, m.x, y - thick / 2, m.z, col);
}
/** A low wall round a roof (solid render) or a glass guard with posts. */
export function parapet(d: SiteDraw, r: PlanRect, y: number, o: { h?: number; glass?: boolean; col?: number } = {}) {
  const h = o.h ?? PARAPET, t = 0.14, col = o.col ?? d.p.slab, m = mid(r);
  const runs: [number, number, number, number][] = [[m.w, t, m.x, r.z1 - t / 2], [m.w, t, m.x, r.z0 + t / 2], [t, m.dd - 2 * t, r.x0 + t / 2, m.z], [t, m.dd - 2 * t, r.x1 - t / 2, m.z]];
  for (const [w, dd, x, z] of runs) {
    if (o.glass) { d.box(d.glassDark, w, h, dd, x, y, z, d.p.glass); d.box(d.plain, w + (w > dd ? 0 : 0.04), 0.05, dd + (w > dd ? 0.04 : 0), x, y + h, z, d.p.frame); }
    else d.box(d.plain, w, h, dd, x, y, z, col);
  }
}

// ------------------------------------------------------------------------------------------------ openings and screens
const litRngs = new WeakMap<SiteDraw, () => number>();
/**
 * A glazed opening on a face of a mass: `at` is the face's plane (z for the street and back faces, x for the sides), `u0…u1` the span along it, `y0…y1`
 * the height. A dark pane in slim bronze frames, a mullion every 1.6 m or so, the pane 4 cm proud of the render so it reads from the street.
 */
export function glazing(d: SiteDraw, o: { face: Face; at: number; u0: number; u1: number; y0: number; y1: number; mullions?: number; frame?: number; lit?: boolean }) {
  const ax = along(o.face), s = out(o.face), len = o.u1 - o.u0, c = (o.u0 + o.u1) / 2, h = o.y1 - o.y0, fr = o.frame ?? d.p.frame, T = 0.05;
  const px = (u: number, off: number) => ax === 'x' ? [u, o.at + s * off] as const : [o.at + s * off, u] as const;
  const [gx, gz] = px(c, T / 2 + 0.01);
  // most panes glow warm at night, some stay dark (a room nobody is in): deterministic from the site
  let lr = litRngs.get(d); if (!lr) litRngs.set(d, lr = siteRng(d, 'lit'));
  const lit = lr() < 0.72 || o.lit === true;
  d.box(lit && o.lit !== false ? d.glass : d.glassDark, ax === 'x' ? len : T, h, ax === 'x' ? T : len, gx, o.y0, gz, d.p.glass);
  const n = o.mullions ?? Math.max(0, Math.floor(len / 1.6) - 1), bar = (u: number, y: number, l: number, v: boolean) => {
    const [bx, bz] = px(u, T + 0.02);
    d.box(d.plain, ax === 'x' ? (v ? 0.06 : l) : 0.07, v ? l : 0.06, ax === 'x' ? 0.07 : (v ? 0.06 : l), bx, y, bz, fr);
  };
  bar(c, o.y0 - 0.03, len + 0.06, false); bar(c, o.y1 - 0.03, len + 0.06, false);        // the sill and the head
  bar(o.u0, o.y0, h, true); bar(o.u1, o.y0, h, true);                                         // the jambs
  for (let k = 1; k <= (d.lite ? Math.min(n, 1) : n); k++) bar(o.u0 + (len * k) / (n + 1), o.y0, h, true);
}
/** Vertical slats on a face (a brise-soleil, an oak claustra, a screen): one piece, a slat every `pitch` m (twice as wide apart on the low preset). */
export function louvres(d: SiteDraw, o: { face: Face; at: number; u0: number; u1: number; y0: number; y1: number; pitch?: number; slat?: number; depth?: number; col?: number }) {
  const ax = along(o.face), s = out(o.face), pitch = (o.pitch ?? 0.2) * (d.lite ? 2 : 1), dep = o.depth ?? 0.1, w = (o.slat ?? 0.07) * (d.lite ? 1.6 : 1), col = o.col ?? d.p.wood;
  const parts: [number, number, number, number, number, number, number][] = [];
  const n = Math.min(60, Math.max(1, Math.floor((o.u1 - o.u0) / pitch)));
  for (let k = 0; k <= n; k++) {
    const u = o.u0 + ((o.u1 - o.u0) * k) / n, off = s * (dep / 2 + 0.03);
    parts.push(ax === 'x' ? [w, o.y1 - o.y0, dep, u, o.y0, o.at + off, col] : [dep, o.y1 - o.y0, w, o.at + off, o.y0, u, col]);
  }
  d.joined(d.plain, parts);
  const mc = (o.u0 + o.u1) / 2, len = o.u1 - o.u0;                                              // the frame: a head and a sill rail
  for (const y of [o.y0, o.y1 - 0.06]) d.box(d.plain, ax === 'x' ? len + 0.12 : dep + 0.04, 0.06, ax === 'x' ? dep + 0.04 : len + 0.12, ax === 'x' ? mc : o.at + s * (dep / 2 + 0.03), y, ax === 'x' ? o.at + s * (dep / 2 + 0.03) : mc, d.p.frame);
}

// ------------------------------------------------------------------------------------------------ balconies, canopies, pergolas
/**
 * A balcony on a face: a slab `depth` deep and `u0…u1` wide at floor level `y` (its top), with a guard 1.05 m high on its three free sides. `guard`:
 * 'glass' (frameless panes on slim posts), 'bars' (bronze verticals) or 'solid' (a low parapet in render).
 */
export function balcony(d: SiteDraw, o: { face: Face; at: number; u0: number; u1: number; y: number; depth?: number; guard?: 'glass' | 'bars' | 'solid'; slab?: number; col?: number }) {
  const ax = along(o.face), s = out(o.face), dep = o.depth ?? 1.6, len = o.u1 - o.u0, c = (o.u0 + o.u1) / 2, guard = o.guard ?? 'glass', H = 1.05, T = 0.22;
  const at = (u: number, off: number) => ax === 'x' ? { x: u, z: o.at + s * off } : { x: o.at + s * off, z: u };
  const sl = at(c, dep / 2);
  d.slab(d.plain, ax === 'x' ? len : dep, T, ax === 'x' ? dep : len, sl.x, o.y - T / 2, sl.z, o.slab ?? o.col ?? d.p.slab);
  // the outer edge (parallel to the face) and the two returns (across it)
  const outer = { q: at(c, dep - 0.04), l: len }, retA = at(o.u0 + 0.04, dep / 2), retB = at(o.u1 - 0.04, dep / 2);
  const gbox = (w: number, dd: number, x: number, z: number) => {
    if (guard === 'glass') { d.box(d.glassDark, w, H, dd, x, o.y, z, d.p.glass); d.box(d.plain, w + (w > dd ? 0.02 : 0.05), 0.04, dd + (w > dd ? 0.05 : 0.02), x, o.y + H, z, d.p.frame); }
    else if (guard === 'solid') d.box(d.plain, w, H - 0.1, dd, x, o.y, z, d.p.slab);
    else { d.box(d.plain, w, 0.05, dd, x, o.y + H - 0.05, z, d.p.frame); d.box(d.plain, w, 0.04, dd, x, o.y + 0.12, z, d.p.frame); }
  };
  gbox(ax === 'x' ? outer.l : 0.05, ax === 'x' ? 0.05 : outer.l, outer.q.x, outer.q.z);
  gbox(ax === 'x' ? 0.05 : dep - 0.1, ax === 'x' ? dep - 0.1 : 0.05, retA.x, retA.z);
  gbox(ax === 'x' ? 0.05 : dep - 0.1, ax === 'x' ? dep - 0.1 : 0.05, retB.x, retB.z);
  if (guard === 'bars' && !d.lite) {                                                // the verticals
    const n = Math.max(2, Math.floor(len / 0.18)), parts: [number, number, number, number, number, number, number][] = [];
    for (let k = 0; k <= n; k++) { const q = at(o.u0 + (len * k) / n, dep - 0.04); parts.push([0.025, H - 0.1, 0.025, q.x, o.y + 0.1, q.z, d.p.frame]); }
    d.joined(d.plain, parts);
  }
}
/** A flat canopy: a slab with an edge, on slim posts at the corners named in `posts` (plan x, z), `y` its top. */
export function canopy(d: SiteDraw, r: PlanRect, y: number, o: { thick?: number; posts?: [number, number][]; col?: number; light?: boolean } = {}) {
  const th = o.thick ?? 0.22, m = mid(r), col = o.col ?? d.p.slab;
  d.slab(d.plain, m.w, th, m.dd, m.x, y - th / 2, m.z, col);
  d.box(d.plain, m.w + 0.02, 0.04, m.dd + 0.02, m.x, y - th, m.z, d.p.frame);
  for (const [x, z] of o.posts ?? []) d.box(d.plain, 0.22, y - th - GROUND, 0.22, x, GROUND, z, d.p.stone);
  if (o.light && !d.lite) for (const sx of [-0.35, 0.35]) d.box(d.bulbs, 0.4, 0.04, 0.2, m.x + sx * m.w, y - th - 0.04, m.z, 0xfff1c8);
}
/** A pergola: posts at the corners, beams along x and slats across them, over a terrace. */
export function pergola(d: SiteDraw, r: PlanRect, y: number, o: { h?: number; slats?: number; col?: number } = {}) {
  const h = o.h ?? 2.5, m = mid(r), col = o.col ?? d.p.frame;
  for (const x of [r.x0 + 0.1, r.x1 - 0.1]) for (const z of [r.z0 + 0.1, r.z1 - 0.1]) d.box(d.plain, 0.16, h, 0.16, x, y, z, col);
  for (const z of [r.z0 + 0.1, r.z1 - 0.1]) d.box(d.plain, m.w, 0.2, 0.2, m.x, y + h, z, col);
  const n = Math.max(2, Math.floor(m.w / (d.lite ? 0.9 : 0.45))), parts: [number, number, number, number, number, number, number][] = [];
  for (let k = 0; k <= n; k++) parts.push([0.07, 0.07, m.dd, r.x0 + (m.w * k) / n, y + h + 0.2, m.z, o.col ?? d.p.wood]);
  d.joined(d.plain, parts);
}

// ------------------------------------------------------------------------------------------------ doors and signs
/**
 * A front door on a face: the leaf (`col`, the palette's wood), a bronze portal round it, a brass pull, a light over it and two stone steps; `portal`
 * adds a taller stone surround (a hotel's or a villa's grand door). `x`, `z`: the door's centre on the face; it faces `face`'s outward way.
 */
export function door(d: SiteDraw, o: { face: Face; x: number; z: number; w?: number; h?: number; col?: number; portal?: boolean; steps?: boolean }) {
  const ax = along(o.face), s = out(o.face), w = o.w ?? 1.3, h = o.h ?? 2.6, col = o.col ?? d.p.wood, T = 0.1;
  const at = (u: number, off: number) => ax === 'x' ? { x: u, z: o.z + s * off } : { x: o.x + s * off, z: u };
  const u0 = ax === 'x' ? o.x : o.z, size = (a: number, b: number): [number, number] => ax === 'x' ? [a, b] : [b, a];
  const box = (b: Batch, a: number, hh: number, dd: number, u: number, off: number, y: number, c: number) => { const [bw, bd] = size(a, dd), q = at(u, off); d.box(b, bw, hh, bd, q.x, y, q.z, c); };
  if (o.portal) { box(d.plain, w + 1.0, h + 0.5, 0.35, u0, 0.17, GROUND, d.p.stone); box(d.plain, w + 1.16, 0.12, 0.45, u0, 0.2, GROUND + h + 0.5, d.p.stoneDark); }
  box(d.plain, w + 0.24, h + 0.12, T + 0.06, u0, 0.2, GROUND, d.p.frame);                      // the bronze portal
  box(d.plain, w, h, T, u0, 0.27, GROUND, col);                                               // the leaf
  if (!d.lite) { box(d.plain, 0.03, 1.1, 0.04, u0 + w * 0.36, 0.33, GROUND + 0.6, d.p.accent); box(d.plain, 0.03, h - 0.2, 0.02, u0, 0.33, GROUND + 0.05, shade(col, 0.7)); }   // the pull, the groove
  box(d.bulbs, 0.34, 0.07, 0.16, u0, 0.4, GROUND + h + 0.14, 0xfff1c8);                         // the light over the door
  if (o.steps !== false) { box(d.plain, w + 0.8, 0.09, 0.7, u0, 0.65, GROUND, d.p.stone); box(d.plain, w + 1.2, 0.09, 0.5, u0, 0.95, GROUND, d.p.stoneDark); }
}
const shade = (c: number, k: number) => { const r = ((c >> 16) & 255) * k, g = ((c >> 8) & 255) * k, b = (c & 255) * k; return (Math.round(r) << 16) | (Math.round(g) << 8) | Math.round(b); };
/**
 * A sign board facing the street from plan (x, z), its centre `y` above the ground: a lit panel (the hub's own sign: its text is drawn on a canvas) on
 * a plain frame. `w`, `h` in metres.
 */
export function nameBoard(d: SiteDraw, text: string, o: { x: number; z: number; y: number; w?: number; h?: number; bg?: string; fg?: string; face?: Face }) {
  const w = o.w ?? 4, h = o.h ?? 0.8, q = d.f.p(o.x, o.z), f = o.face ?? 'street', yaw = d.f.rot(f === 'street' ? 0 : f === 'back' ? Math.PI : f === 'right' ? Math.PI / 2 : -Math.PI / 2);
  d.sign(text, o.bg ?? '#14323a', o.fg ?? '#f4e6bd', q.x, o.y, q.z, yaw, w, h);
}

