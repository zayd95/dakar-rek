import { chromium } from 'playwright';
import { realTouch, boardVehicle, padRig } from '../scripts/lib/realTouch.mjs';
const [base = 'http://127.0.0.1:4700/'] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
await ctx.addInitScript(() => { try { localStorage.setItem('dakarrek.quality', 'low'); } catch {} });
const page = await ctx.newPage(); page.setDefaultTimeout(300000);
page.on('pageerror', e => console.log('PAGEERROR', e.message));
const d = (fn, a) => page.evaluate(fn, a);
await page.goto(`${base}?debug&touch&heure=15&argent=4500000`);
await page.waitForFunction(() => window.__dakar?.pos && window.__dakar.pos().hub && window.__dakar.vtc, null, { timeout: 300000 });
const t = await realTouch(page);
await page.waitForFunction(() => window.__dakar.teranga.info().floor.length > 0, null, { timeout: 300000 });
await d(() => window.__dakar.teranga.own());
await page.waitForFunction(() => window.__dakar.teranga.info().owned && window.__dakar.teranga.info().here, null, { timeout: 300000 });
await d(() => window.__dakar.teranga.place(-90, 3.2, Math.PI / 2));
await d(() => window.__dakar.place(-90, 0.6, 0));
await page.waitForTimeout(800);
await boardVehicle(page, t, 'teranga');
await page.waitForTimeout(1500);
await page.screenshot({ path: '/tmp/claude-0/comb/feel/pad-idle.png' }); console.log('classes', await d(() => [...document.querySelectorAll('#ridepad button')].map(b => b.className + ':' + Math.round(b.getBoundingClientRect().width) + 'x' + Math.round(b.getBoundingClientRect().height)).join(' | ')));
const R = await padRig(page, t);
console.log('rig', JSON.stringify(R, (k, v) => typeof v === 'function' ? undefined : v));
// hold gas at toe-ish and steer right at the rim for a moment
const rocker = R.rocker(2), gas = R.gas(5);
await gas(true); await rocker(1); await page.waitForTimeout(2500);
await page.screenshot({ path: '/tmp/claude-0/comb/feel/pad-driving.png' });
const a1 = await d(() => window.__dakar.teranga.at());
console.log('at', JSON.stringify(a1));
await rocker(-1); await page.waitForTimeout(2500);
const a2 = await d(() => window.__dakar.teranga.at());
console.log('at2', JSON.stringify(a2));
await gas(false); await rocker(0);
await browser.close();
