import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--no-sandbox'] });
const c = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const p = await c.newPage(); const errs = [], bad = [], glb = [];
p.on('pageerror', e => errs.push(e.message)); p.on('response', r => { if (r.status() >= 400) bad.push(r.status() + ' ' + r.url()); if (/\.glb/.test(r.url())) glb.push(r.status() + ' ' + r.url().split('/').slice(-2).join('/')); });
await p.goto('http://127.0.0.1:4710/index.html?debug', { timeout: 120000 });
await p.waitForTimeout(8000);
await p.getByText('Vitrine du propriétaire').first().click();
await p.waitForTimeout(40000);
console.log(JSON.stringify({ text: (await p.evaluate(() => document.body.innerText)).replace(/\s+/g, ' ').slice(0, 400), errs, bad, glb }));
await p.screenshot({ path: '/tmp/claude-0/comb/art-start.png' });
await b.close();
